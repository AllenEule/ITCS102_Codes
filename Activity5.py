#arithmetic operators = mathematical symbols 
# + - addition 
# - - subtraction
# * - multiplication 
# / - division 
# // - floor division
# ** - exponentation 
# % - modulus


a = 10 
b = 25 
sum = a + b
diff = a - b

print("The sum of ",a,"plus ",b,"is ",sum)
print("The sum of ",a,"minus",b,"is ",diff)
print("The sum of ",a,"times ",b,"is ",a*b)
print("The sum of ",a,"division ",b,"is ",a/b)
print("The sum of ",a,"floor division ",b,"is ",a//b)
print("The sum of ",a,"exponentation ",b,"is ",a**b)
print("The sum of ",a,"modulus ",b,"is ",a%b)













